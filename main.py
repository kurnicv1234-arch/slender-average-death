    def play_cutscene_scream(self):
        # Короткий синтезированный хоррор-эффект; если аудиоустройство недоступно,
        # катсцена продолжится без звука.
        try:
            mixer_info = pygame.mixer.get_init()
            if not mixer_info:
                return
            rate, sample_format, channels = mixer_info
            if sample_format != -16:
                return
            duration = 1.15
            n = int(rate * duration)
            tt = np.arange(n, dtype=np.float32) / float(rate)
            freq = 520.0 - 190.0 * (tt / duration) + 42.0 * np.sin(tt * 17.0)
            phase = 2.0 * math.pi * np.cumsum(freq) / float(rate)
            noise = np.random.RandomState(91).normal(0.0, 1.0, n).astype(np.float32)
            envelope = np.clip(tt / 0.08, 0.0, 1.0) * np.clip((duration - tt) / 0.20, 0.0, 1.0)
            wave = (np.sin(phase) + 0.28 * np.sin(phase * 2.03) + 0.10 * noise)
            audio = np.clip(wave * envelope * 10500.0, -32767, 32767).astype(np.int16)
            if channels == 2:
                audio = np.column_stack((audio, audio))
            sound = pygame.sndarray.make_sound(audio)
            sound.set_volume(0.58)
            sound.play()
        except Exception:
            pass

