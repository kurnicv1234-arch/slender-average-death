    @staticmethod
    def _gradient(w, h, amax):
        a = (np.linspace(0, 1, h, dtype=np.float32) ** 1.6 * amax).astype(np.uint8)
        arr = np.zeros((h, w, 4), np.uint8)
        arr[..., 3] = a[:, None]
        return pygame.image.frombuffer(arr.tobytes(), (w, h), 'RGBA')

    @staticmethod
    def _soft_ellipse(w, h):
        yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
        r = ((xx - w / 2) / (w / 2)) ** 2 + ((yy - h / 2) / (h / 2)) ** 2
        a = (np.exp(-r * 2.2) * 120).astype(np.uint8)
        arr = np.zeros((h, w, 4), np.uint8)
        arr[..., 3] = a
        return pygame.image.frombuffer(arr.tobytes(), (w, h), 'RGBA')

