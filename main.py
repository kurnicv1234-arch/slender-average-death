class ObjView:
    """Рисует 3D-модель чётко (в полном разрешении экрана) с мягкой подсветкой."""
    LV = np.array([-0.45, -0.65, -0.62], np.float32)

    def __init__(self, model, size):
        self.m = model
        self.size = int(min(size, 720))      # внутреннее разрешение; на экран растягивается
        self.ss = 1.25
        self.S = int(self.size * self.ss)
        self.buf = pygame.Surface((self.S, self.S), pygame.SRCALPHA)
        self.D = 6.0
        rb = model['radius']
        self.fo = 0.5 * self.S * (self.D - rb) / rb * 0.98 * model.get('fit', 1.0)
        self.Lv = self.LV / np.linalg.norm(self.LV)

    def render(self, yaw, pitch, zoom=1.0):
        m = self.m
        Rm = rot_x(pitch) @ rot_y(yaw)
        Rt = Rm.T
        cam = m['verts'] @ Rt
        cam[:, 2] += self.D
        zz = np.maximum(cam[:, 2], 0.5)
        fo = self.fo * zoom
        px = (self.S / 2 + fo * cam[:, 0] / zz)
        py = (self.S / 2 + fo * cam[:, 1] / zz)
        pts = np.stack([px, py], 1).tolist()
        nrm = m['nrm'] @ Rt
        ctr = m['ctr'] @ Rt
        ctr[:, 2] += self.D
        vdir = -ctr / np.maximum(np.linalg.norm(ctr, axis=1, keepdims=True), 1e-6)
        vis = (nrm * vdir).sum(1) > 0.01
        diff = np.clip(nrm @ self.Lv, 0, 1)
        hv = self.Lv[None, :] + vdir
        hv /= np.maximum(np.linalg.norm(hv, axis=1, keepdims=True), 1e-6)
        sp = np.clip((nrm * hv).sum(1), 0, 1) ** m['shin'] * m['spec']
        rim = 0.10 * (1.0 - np.abs((nrm * vdir).sum(1)))
        col = m['col'] * (0.34 + 0.80 * diff + rim)[:, None] + 255.0 * sp[:, None]
        col = np.clip(col, 0, 255).astype(np.int32).tolist()
        keyz = (m['keyc'] @ Rt)[:, 2] + m['bias'] - m['decal'] * 1e-3
        order = np.argsort(-keyz)
        self.buf.fill((0, 0, 0, 0))
        st, cn = m['start'], m['count']
        draw = pygame.draw.polygon
        for i in order.tolist():
            if not vis[i]:
                continue
            a = int(st[i])
            draw(self.buf, col[i], pts[a:a + int(cn[i])])
        return self.buf


