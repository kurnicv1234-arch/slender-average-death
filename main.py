            sx, sy, dep = pr
            ix, iy = int(sx), int(sy)
            if not (0 <= ix < R.W and 0 <= iy < R.H) or dep >= R.zpix[iy, ix] - 0.04:
                continue
            atten = 1.0 / (1.0 + (dep / 3.4) ** 2.2)
            lit = float(R.cone[iy, ix]) * atten * R.power * R.flick
            v = int(255 * clamp(0.05 + 1.15 * lit, 0.0, 1.0) * clamp((dep - 0.2) / 0.5, 0.0, 1.0))
            if v < 22:
                continue
            side = max(2, int(sc * (0.55 if dep > 2.0 else 0.9)))
            scr.fill((v, v, v), (int(sx * sc - side / 2), int(sy * sc - side / 2), side, side))

