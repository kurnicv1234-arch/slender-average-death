    def on_down(self, pid, x, y):
        if self.menu_state != 'game':
            self.menu_pressed[pid] = (x, y)
            return
        # Каждый палец хранится отдельно по finger_id: один может держать
        # джойстик движения, пока второй независимо управляет обзором.
        if self.dead:
            if self.dead_t > 2.4:
                self.restart()
            return
        U, sw, sh = self.U, self.sw, self.sh
        p = Ptr(pid, x, y, 'look', self.t)
        # клик по кнопке/зоне миникарты
        if self.mode == 'explore':
            if self.show_minimap and self.minimap_rect.collidepoint(x, y):
                p.role = 'btn_minimap'
                self.ptrs[pid] = p
                return
            if (not self.show_minimap and getattr(self, 'minimap_btn_center', None)
                    and math.hypot(x - self.minimap_btn_center[0], y - self.minimap_btn_center[1]) < self.minimap_btn_r + 8 * U):
                p.role = 'btn_minimap'
                self.ptrs[pid] = p
                return
        if self.mode == 'explore':
            if self.target and self.btn_a > 0.3 and self.inspect_rect().collidepoint(x, y):
                p.role = 'btn_inspect'
            elif x < sw * 0.5 and not any(q.role == 'stick' for q in self.ptrs.values()) and not self.show_minimap:
                p.role = 'stick'
                p.ox = clamp(x, 120 * U, sw * 0.5 - 40 * U)
                p.oy = clamp(y, sh * 0.5, sh - 130 * U)
                p.sx, p.sy = p.ox, p.oy
            else:
                p.role = 'look'
        else:
            p.role = 'obj'
            if y > sh - 190 * U and self.leaving is None:
                cell = int(x / (sw / 3.0))
                if cell >= 1:
                    p.role = 'btn_take' if cell == 1 else 'btn_back'
                    p.cell = cell
                    self.pressed_cell = cell
        self.ptrs[pid] = p

    def on_move(self, pid, x, y):
        if self.menu_state != 'game':
            if pid in self.menu_pressed:
                self.menu_pressed[pid] = (x, y)
            return
        p = self.ptrs.get(pid)
        if not p:
            return
        dx, dy = (x - p.x) / self.U, (y - p.y) / self.U
        p.dist += math.hypot(dx, dy)
        p.x, p.y = x, y
        if p.role == 'look':
            self.yaw_t += dx * LOOK_SENS
            self.pitch_t = clamp(self.pitch_t - dy * LOOK_SENS, -1.0, 0.85)
            self.frame_ldx += dx
            self.frame_ldy += dy
        elif p.role == 'obj':
            n_obj = sum(1 for q in self.ptrs.values() if q.role == 'obj')
            if n_obj >= 2:
                a, b = [q for q in self.ptrs.values() if q.role == 'obj'][:2]
                d_new = math.hypot(a.x - b.x, a.y - b.y)
                other = b if a is p else a
                d_old = math.hypot((p.x - dx * self.U) - other.x, (p.y - dy * self.U) - other.y)
                if d_old > 20:
                    self.zoom_t = clamp(self.zoom_t * d_new / d_old, 0.7, 1.7)
            elif self.leaving is None:
                self.o_yaw += dx * 0.0115
                self.o_pitch = clamp(self.o_pitch + dy * 0.0115, -1.4, 1.4)
                self.frame_odx += dx
                self.frame_ody += dy

    def on_up(self, pid, x, y):
        if self.menu_state != 'game':
            was_pressed = self.menu_pressed.pop(pid, None)
            if was_pressed and math.hypot(x - was_pressed[0], y - was_pressed[1]) < 35 * self.U:
                self.menu_click(x, y)
            return
        p = self.ptrs.pop(pid, None)
        if not p:
            return
        U, sw = self.U, self.sw
        if p.role == 'btn_minimap' and p.dist < 25:
            if self.show_minimap:
                # тап по самой карте или кнопке — закрыть
                self.show_minimap = False
            else:
                self.show_minimap = True
                self.vx = self.vy = 0.0
                self.toast('Миникарта (M / тап — закрыть)')
        elif p.role == 'look' and p.dist < 16 and self.t - p.t0 < 0.35:
            self.tap(x, y)
        elif p.role == 'btn_inspect' and self.inspect_rect().collidepoint(x, y) and self.target:
            self.start_inspect(self.target)
        elif p.role in ('btn_take', 'btn_back'):
            if int(x / (sw / 3.0)) == p.cell and y > self.sh - 230 * U:
                self.take() if p.role == 'btn_take' else self.back()
        if p.role == 'stick':
            pass
        if not any(q.role.startswith('btn_') for q in self.ptrs.values()):
            self.pressed_cell = None

    def tap(self, x, y):
        """Тап по предмету на экране."""
        cam = (self.px, self.py, self.yaw, self.pitch, self.camh)
        sc = self.sw / self.bw
        # Тап по двери открывает/закрывает её, если игрок стоит рядом.
        bx, by = x / sc, y / sc
        best, bt = None, 1e9
        for door in self.doors:
            if math.hypot(door['x'] - self.px, door['y'] - self.py) > 2.6:
                continue
            tt = self.R.door_hit(cam, bx, by, self.door_segment(door))
            if tt is not None and tt < bt:
                best, bt = door, tt
        if best is not None:
            self.toggle_door(best)
            return
        for it in self.items:
            if it.taken:
                continue
            if math.hypot(it.x - self.px, it.y - self.py) > 2.1:
                continue
            if not self.line_clear(self.px, self.py, it.x, it.y):
                continue
            pr = self.R.project(cam, it.x, it.y, it.size * 0.45)
            if not pr:
                continue
            ix, iy, dep = pr[0] * sc, pr[1] * sc, pr[2]
            rad = max(46 * self.U, self.R.f * it.size / dep * sc * 0.8)
            if math.hypot(ix - x, iy - y) < rad:
                if dep < 2.1:
                    self.start_inspect(it)
                else:
                    self.toast('Подойдите ближе')
                return

