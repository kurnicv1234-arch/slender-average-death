def clamp(v, a, b):
    return a if v < a else b if v > b else v


def lerp(a, b, t):
    return a + (b - a) * t


def damp(cur, tgt, rate, dt):
    """Экспоненциальное сглаживание, не зависит от FPS."""
    return cur + (tgt - cur) * (1.0 - math.exp(-rate * dt))


def damp_angle(cur, tgt, rate, dt):
    d = (tgt - cur + math.pi) % (2 * math.pi) - math.pi
    return cur + d * (1.0 - math.exp(-rate * dt))


