def make_textures():
    rs = np.random.RandomState(11)

    def noise(h, w, a):
        return rs.randint(-a, a + 1, (h, w, 1)).astype(np.int16)

    # пол: утоптанная земля с мелким щебнем (как на референсе)
    def pnoise(freq, seed):
        r = np.random.RandomState(seed)
        g = r.rand(freq, freq).astype(np.float32)
        big = np.kron(g, np.ones((64 // freq, 64 // freq), np.float32))
        k = np.ones(64 // freq, np.float32) / (64 // freq)
        for ax in (0, 1):                      # циклическое сглаживание — текстура бесшовная
            big = sum(np.roll(big, s, ax) for s in range(-(64 // freq) // 2, (64 // freq) // 2 + 1)) / (64 // freq + 1)
        return big - big.mean()

    dirt = np.zeros((64, 64, 3), np.float32)
    dirt[:] = (92, 70, 50)
    m = pnoise(8, 1) * 90 + pnoise(16, 2) * 60
    dirt += m[..., None] * np.array([1.0, 0.85, 0.7], np.float32)
    dirt += rs.randint(-9, 10, (64, 64, 1)).astype(np.float32)
    pebble = rs.rand(64, 64) < 0.030
    dirt[pebble] = (146, 128, 104) + rs.randint(-20, 20, (int(pebble.sum()), 1))
    dark = rs.rand(64, 64) < 0.05
    dirt[dark] *= 0.55
    floor = np.clip(dirt, 0, 255).astype(np.uint8)

    # стена: бетон с серо-зелёным налётом, швы панелей, грязь и ржавые крапинки внизу
