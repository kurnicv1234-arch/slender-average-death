    def build_batteries(self):
        rs = np.random.RandomState(33)
        self.batteries = []
        cache = {}
        chosen = []
        start = (START_CELL[0] + .5, START_CELL[1] + .5)

        def mdl(z):
            k = round(z, 3)
            if k not in cache:
                cache[k] = make_battery_model(k)
            return cache[k]

        def sep_ok(x, y, sep):
            return (math.hypot(x - start[0], y - start[1]) > 3.0 and
                    all(math.hypot(x - cx, y - cy) >= sep for cx, cy in chosen))

        def add(x, y, z):
            self.batteries.append({'x': x, 'y': y, 'z': z, 'model': mdl(z), 'got': False})

        # 1) на мебели: бочки, ящики, столы, полки, шкафы...
        cand = [d for d in self.decor if d['kind'] in BATT_KINDS]
        n_f = 0
        for i in rs.permutation(len(cand)):
            if n_f >= 9:
                break
            d = cand[int(i)]
            if not sep_ok(d['x'], d['y'], 9.0):
                continue
            m = d['model']
            for _ in range(1 + int(rs.rand() < 0.4)):
                if d['kind'] == 'shelf':
                    ox, oy = rs.uniform(-.05, .05), rs.uniform(-.04, .04)
                    z = m['surf'][int(rs.randint(len(m['surf'])))]
                else:
                    ox, oy = rs.uniform(-.3, .3) * m['hx'], rs.uniform(-.3, .3) * m['hy']
                    z = m['top']
                add(d['x'] + d['c'] * ox - d['s'] * oy, d['y'] + d['s'] * ox + d['c'] * oy, z)
            chosen.append((d['x'], d['y']))
            n_f += 1
        # 2) за дверьми — в проходе сразу за дверью
        regs = [d for d in self.doors if d.get('kind') == 'door']
        n_d = 0
        for i in rs.permutation(len(regs)):
            if n_d >= 3:
                break
            d = regs[int(i)]
            ax, ay = d['axis']
            sg = 1 if rs.rand() < .5 else -1
            for sgn in (sg, -sg):
                cx, cy = d['gx'] + int(round(ax * sgn)), d['gy'] + int(round(ay * sgn))
                x, y = cx + .5 + rs.uniform(-.2, .2), cy + .5 + rs.uniform(-.2, .2)
                if (0 <= cy < self.R.mh and 0 <= cx < self.R.mw and self.R.map[cy, cx] == 0
                        and self.free(x, y, .16) and sep_ok(x, y, 6.0)):
                    add(x, y, 0.0)
                    if rs.rand() < .4:
                        add(x + .12, y + .1, 0.0)
                    chosen.append((x, y))
                    n_d += 1
                    break
        # 3) внутри шкафов-ниш (нужно открыть дверцы)
        cl = list(getattr(self, 'closets', []))
        n_w = 0
        for i in rs.permutation(len(cl)):
            if n_w >= 3:
                break
            cx, cy = cl[int(i)]
            x, y = cx + .5, cy + .5
            if sep_ok(x, y, 6.0):
                add(x, y, 0.0)
                chosen.append((x, y))
                n_w += 1

    def update_battery(self, dt):
        if not self.won:
            self.battery = max(0.0, self.battery - dt / BATT_LIFE)
        b = self.battery
        p = 0.07 + 0.93 * clamp(b / 0.7, 0.0, 1.0) ** 0.75
        if b < 0.18:                                     # у самого конца фонарик мигает
            fl = 0.5 + 0.5 * math.sin(self.t * 31.0) * math.sin(self.t * 13.7)
            p *= 0.55 + 0.45 * fl
            if b < 0.1 and int(self.t * 7.0) % 11 == 0:
                p *= 0.2
        # случайные «моргания» фонарика: чем меньше заряд, тем чаще и дольше
        if b < 0.8:
            if self.flk_left > 0.0:
                self.flk_left -= dt
                on = (math.sin(self.t * 38.0) + math.sin(self.t * 23.0 + 1.3)) > 0.35
                p *= 1.0 if on else 0.10
            else:
                self.flk_t -= dt
                if self.flk_t <= 0.0:
                    self.flk_left = float(self.sl_rs.uniform(0.25, 0.5 + 0.9 * (1.0 - b)))
                    self.flk_t = float(self.sl_rs.uniform(5.0, 16.0) * (0.25 + 0.75 * b))
        self.R.power = p
        if b > 0.4:
            self.bat_warn = 0
        elif b < 0.08 and self.bat_warn < 2:
            self.bat_warn = 2
            self.toast('Фонарик почти разряжен!')
        elif b < 0.25 and self.bat_warn < 1:
            self.bat_warn = 1
            self.toast('Фонарик садится — ищите батарейки')
        if self.mode == 'explore':
            for bt in self.batteries:
                if bt['got'] or abs(bt['x'] - self.px) > 0.95 or abs(bt['y'] - self.py) > 0.95:
                    continue
                if math.hypot(bt['x'] - self.px, bt['y'] - self.py) > 0.95:
                    continue
                if not self.line_clear(self.px, self.py, bt['x'], bt['y']):
                    continue
                bt['got'] = True
                self.battery = min(1.0, self.battery + BATT_RESTORE)
                self.toast('Батарейка +%d%%  (заряд %d%%)' % (round(BATT_RESTORE * 100), round(self.battery * 100)))

