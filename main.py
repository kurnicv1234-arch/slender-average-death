    def new_mote(self):
        rs = self.sl_rs
        x, y = self.px, self.py
        for _ in range(12):
            a, r = rs.uniform(0, 2 * math.pi), 0.7 + 4.2 * math.sqrt(rs.rand())
            cx, cy = self.px + math.cos(a) * r, self.py + math.sin(a) * r
            ix, iy = int(cx), int(cy)
            if 0 <= iy < self.R.mh and 0 <= ix < self.R.mw and self.R.map[iy, ix] == 0:
                x, y = cx, cy
                break
        return {'x': x, 'y': y, 'z': float(rs.uniform(0.06, 0.95)),
                'vx': float(rs.uniform(-0.05, 0.05)), 'vy': float(rs.uniform(-0.05, 0.05)),
                'vz': float(rs.uniform(-0.02, 0.025)), 'ph': float(rs.uniform(0, 6.28))}

    def update_motes(self, dt):
        t, mp = self.t, self.R.map
        for i, m in enumerate(self.motes):
            ph = m['ph']
            m['x'] += (m['vx'] + 0.035 * math.sin(t * 0.7 + ph)) * dt
            m['y'] += (m['vy'] + 0.035 * math.cos(t * 0.6 + ph * 1.7)) * dt
            m['z'] += (m['vz'] + 0.015 * math.sin(t * 1.1 + ph * 2.0)) * dt
            if m['z'] < 0.04 or m['z'] > 0.97:
                m['vz'] = -m['vz']
                m['z'] = clamp(m['z'], 0.05, 0.96)
            ix, iy = int(m['x']), int(m['y'])
            far = (m['x'] - self.px) ** 2 + (m['y'] - self.py) ** 2 > 5.6 * 5.6
            if far or not (0 <= iy < self.R.mh and 0 <= ix < self.R.mw) or mp[iy, ix] != 0:
                self.motes[i] = self.new_mote()

    def draw_motes(self, cam, sc):
        R, scr = self.R, self.screen
