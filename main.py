    def draw_minimap(self):
        """Миникарта в правом верхнем углу: точная картинка + положение и направление игрока."""
        if not self.show_minimap:
            return
        scr, U = self.screen, self.U
        side = self.minimap_side
        side_h = self.minimap_h
        surf = self.minimap_base.copy()

        # --- перевод мировых координат в координаты на картинке ---
        # content на оригинале: (cx0, cy0, cw, ch)
        cx0, cy0, cw, ch = self.minimap_content
        mw = max(1, self.R.mw)
        mh = max(1, self.R.mh)

        def world_to_img(wx, wy):
            # нормализуем 0..1 по миру
            nx = clamp(wx / mw, 0.0, 1.0)
            ny = clamp(wy / mh, 0.0, 1.0)
            # в пиксели исходного рисунка
            ix = cx0 + nx * cw
            iy = cy0 + ny * ch
            # в пиксели масштабированной картинки
            ox, oy = self.minimap_img_offset
            nw, nh = self.minimap_img_size
            sx = ox + (ix / self.minimap_src_w) * nw
            sy = oy + (iy / self.minimap_src_h) * nh
            return sx, sy

        # предметы (маленькие точки)
        for it in self.items:
            if it.taken:
                continue
            ix, iy = world_to_img(it.x, it.y)
            r = max(2, int(2.6 * U))
            pygame.draw.circle(surf, (50, 100, 170), (int(ix), int(iy)), r + 1)
            pygame.draw.circle(surf, (160, 200, 255), (int(ix), int(iy)), r)

        # игрок: треугольник-стрелка в направлении yaw
        px, py = world_to_img(self.px, self.py)
        ang = self.yaw
        length = max(8.0, 11.0 * U)
        width = length * 0.58
        tip_x = px + math.cos(ang) * length
        tip_y = py + math.sin(ang) * length
        bx = px - math.cos(ang) * length * 0.38
        by = py - math.sin(ang) * length * 0.38
        left_x = bx + math.cos(ang + math.pi / 2) * width
        left_y = by + math.sin(ang + math.pi / 2) * width
        right_x = bx + math.cos(ang - math.pi / 2) * width
        right_y = by + math.sin(ang - math.pi / 2) * width
        pts = [(int(tip_x), int(tip_y)), (int(left_x), int(left_y)), (int(right_x), int(right_y))]
        # тень
        shadow = [(p[0] + 1, p[1] + 1) for p in pts]
        pygame.draw.polygon(surf, (30, 15, 5, 180), shadow)
        pygame.draw.polygon(surf, (210, 35, 30), pts)
        pygame.draw.polygon(surf, (255, 100, 70), pts, max(1, int(1.4 * U)))
        # яркая точка в центре
        pygame.draw.circle(surf, (255, 230, 180), (int(px), int(py)), max(2, int(2.4 * U)))
        pygame.draw.circle(surf, (180, 40, 30), (int(px), int(py)), max(1, int(1.2 * U)))

        # рамка поверх
        pygame.draw.rect(surf, (55, 40, 25), (0, 0, side, side_h), max(2, int(2.5 * U)))

        # выводим
        rect = self.minimap_rect
        shadow_s = pygame.Surface((side + 8, side_h + 8), pygame.SRCALPHA)
        shadow_s.fill((0, 0, 0, 80))
        scr.blit(shadow_s, (rect.x + 3, rect.y + 3))
        scr.blit(surf, rect.topleft)
        # подсказка закрытия
        self.blit_text('M / тап — закрыть', 18 * U, rect.centerx, rect.bottom + 14 * U,
                       (230, 220, 200), alpha=190)

