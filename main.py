def make_sprite(rows):
    h, w = len(rows), len(rows[0])
    rgb = np.zeros((h, w, 3), np.float32)
    a = np.zeros((h, w), bool)
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch in SPR_PAL:
                rgb[y, x] = SPR_PAL[ch]
                a[y, x] = True
    return rgb, a


