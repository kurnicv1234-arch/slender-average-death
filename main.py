def spr_wheel(variant=0):
    c = Canvas(32)
    cx, cy, R = 16.0, 16.5, 14.5
    wood, iron, spoke = (112, 78, 46), (70, 68, 64), (124, 88, 52)
    d = np.hypot(c.xx - cx, c.yy - cy)
    ang = np.arctan2(c.yy - cy, c.xx - cx)
    gap_c = 0.6 if variant == 0 else -2.3
    gap_w = 0.55
    in_gap = np.abs(((ang - gap_c + math.pi) % (2 * math.pi)) - math.pi) < gap_w
    c.paint((d <= R) & (d >= R - 3.2) & ~in_gap, wood)
    c.paint((d <= R) & (d >= R - 1.3) & ~in_gap, iron)
    rs = np.random.RandomState(40 + variant)
    for k in range(8):
        a = k * math.pi / 4 + 0.2
        da = abs(((a - gap_c + math.pi) % (2 * math.pi)) - math.pi)
        length = R - 3.0
        if da < gap_w + 0.3:
            length = 5.0 + rs.rand() * 3
        elif rs.rand() < 0.15:
            length = 7.0 + rs.rand() * 3
        c.line(cx, cy, cx + math.cos(a) * length, cy + math.sin(a) * length, spoke, 1.9)
    c.paint(d <= 3.4, (74, 50, 32))
    c.a[d <= 1.2] = False
    c.rgb *= (1.12 - 0.30 * ((c.xx - cx) + (c.yy - cy)) / (2 * R))[..., None]
    c.speckle(6, 21 + variant)
    c.outline(0.5)
    return c.finish()


