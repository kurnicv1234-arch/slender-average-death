def rot_x(a):
    c, s = math.cos(a), math.sin(a)
    return np.array([[1, 0, 0], [0, c, -s], [0, s, c]], np.float32)


def rot_y(a):
    c, s = math.cos(a), math.sin(a)
    return np.array([[c, 0, -s], [0, 1, 0], [s, 0, c]], np.float32)


def rot_z(a):
    c, s = math.cos(a), math.sin(a)
    return np.array([[c, -s, 0], [s, c, 0], [0, 0, 1]], np.float32)


class MeshBuilder:
    def __init__(self, seed=3):
        self.rs = np.random.RandomState(seed)
        self.polys, self.col, self.spec, self.shin = [], [], [], []
        self.bias, self.nrm, self.ctr, self.keyc, self.is_decal = [], [], [], [], []

    def face(self, pts, color, solid_c, spec=0.15, shin=24, bias=0.0, nrm=None, keyc=None, decal=False):
        pts = np.asarray(pts, np.float32)
        c = pts.mean(0)
        if nrm is None:
            n = np.cross(pts[1] - pts[0], pts[2] - pts[0])
            ln = float(np.linalg.norm(n))
            n = n / ln if ln > 1e-9 else np.array([0, 0, -1], np.float32)
            if float(np.dot(n, c - solid_c)) < 0:
                n = -n
        else:
            n = np.asarray(nrm, np.float32)
        self.polys.append(pts)
        self.col.append(color)
        self.spec.append(spec)
        self.shin.append(shin)
        self.bias.append(bias)
        self.nrm.append(n)
        self.ctr.append(c)
        self.keyc.append(c if keyc is None else keyc)
        self.is_decal.append(decal)
        return len(self.polys) - 1

    def box(self, center, size, colors, R=None, spec=0.2, shin=24, bias=0.0):
        center = np.array(center, np.float32)
        R = np.eye(3, dtype=np.float32) if R is None else R
        h = np.array(size, np.float32) / 2
        info = {}
        for ax in range(3):
            for sg in (-1, 1):
                name = ('-+'[sg > 0]) + 'xyz'[ax]
                a1, a2 = [i for i in range(3) if i != ax]
                pts = []
                for s1, s2 in ((-1, -1), (1, -1), (1, 1), (-1, 1)):
                    p = np.zeros(3, np.float32)
                    p[ax], p[a1], p[a2] = sg * h[ax], s1 * h[a1], s2 * h[a2]
                    pts.append(R @ p + center)
                col = colors[name] if isinstance(colors, dict) else colors
                idx = self.face(pts, col, center, spec, shin, bias)
                info[name] = (idx, ax, sg, a1, a2)
        return {'c': center, 'R': R, 'h': h, 'faces': info, 'bias': bias}

    def decal(self, bx, name, c1, c2, w1, w2, color, spec=0.2, shin=24, lift=0.003):
        idx, ax, sg, a1, a2 = bx['faces'][name]
        pts = []
        for s1, s2 in ((-1, -1), (1, -1), (1, 1), (-1, 1)):
            p = np.zeros(3, np.float32)
            p[ax] = sg * (bx['h'][ax] + lift)
            p[a1] = c1 + s1 * w1 / 2
            p[a2] = c2 + s2 * w2 / 2
            pts.append(bx['R'] @ p + bx['c'])
        self.face(pts, color, None, spec, shin, bx['bias'], nrm=self.nrm[idx], keyc=self.ctr[idx], decal=True)

    def cylinder(self, center, r, h, color, caps=None, n=28, R=None, jitter=0, spec=0.15, shin=24, bias=0.0):
        center = np.array(center, np.float32)
        R = np.eye(3, dtype=np.float32) if R is None else R
        info = {}
        for i in range(n):
            a0, a1 = 2 * math.pi * i / n, 2 * math.pi * (i + 1) / n
            loc = [(r * math.cos(a0), -h / 2, r * math.sin(a0)), (r * math.cos(a1), -h / 2, r * math.sin(a1)),
                   (r * math.cos(a1), h / 2, r * math.sin(a1)), (r * math.cos(a0), h / 2, r * math.sin(a0))]
            pts = [R @ np.array(p, np.float32) + center for p in loc]
            j = self.rs.randint(-jitter, jitter + 1) if jitter else 0
            col = tuple(int(clamp(c + j, 0, 255)) for c in color)
            self.face(pts, col, center, spec, shin, bias)
        if caps:
            for sg, cc in ((1, caps[0]), (-1, caps[1])):
                if cc is None:
                    continue
                loc = [(r * math.cos(2 * math.pi * i / n), sg * h / 2, r * math.sin(2 * math.pi * i / n))
                       for i in range(n)]
                pts = [R @ np.array(p, np.float32) + center for p in loc]
                idx = self.face(pts, cc, center, spec + 0.15, shin + 20, bias)
                info['top' if sg > 0 else 'bot'] = idx
        return {'c': center, 'R': R, 'r': r, 'h': h, 'faces': info, 'bias': bias}

    def cap_decal(self, cyl, which, r, color, dx=0.0, dz=0.0, n=20, sx=1.0, spec=0.3, shin=30):
        idx = cyl['faces'][which]
        sg = 1 if which == 'top' else -1
        loc = [(dx + r * sx * math.cos(2 * math.pi * i / n), sg * (cyl['h'] / 2 + 0.003),
                dz + r * math.sin(2 * math.pi * i / n)) for i in range(n)]
        pts = [cyl['R'] @ np.array(p, np.float32) + cyl['c'] for p in loc]
        self.face(pts, color, None, spec, shin, cyl['bias'], nrm=self.nrm[idx], keyc=self.ctr[idx], decal=True)

    def finish(self):
        counts = np.array([len(p) for p in self.polys])
        starts = np.concatenate([[0], np.cumsum(counts)[:-1]])
        m = {
            'verts': np.concatenate(self.polys).astype(np.float32),
            'start': starts, 'count': counts,
            'col': np.array(self.col, np.float32), 'spec': np.array(self.spec, np.float32),
            'shin': np.array(self.shin, np.float32), 'bias': np.array(self.bias, np.float32),
            'nrm': np.array(self.nrm, np.float32), 'ctr': np.array(self.ctr, np.float32),
            'keyc': np.array(self.keyc, np.float32), 'decal': np.array(self.is_decal, np.float32),
        }
        # ось Y модели направлена вверх, а на экране вниз — переворачиваем
        for k in ('verts', 'nrm', 'ctr', 'keyc'):
            m[k][:, 1] *= -1
        m['radius'] = float(np.linalg.norm(m['verts'], axis=1).max())
        m['fit'] = 1.0
        return m


