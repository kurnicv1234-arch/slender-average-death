# ------------------------------------------------ настоящие 3D-модели мебели
# Каждая модель — набор объёмных примитивов (параллелепипеды и вертикальные
# цилиндры). Мир рисуется трассировкой лучей по каждому пикселю, поэтому мебель
# — реальный объект в комнате: можно обойти кругом и увидеть все стороны,
# она не «поворачивается» за игроком, как плоская картинка.
def _tint(parts, k):
    out = []
    for p in parts:
        if p[0] == 'cyl':
            q = list(p)
            q[6] = tuple(min(255, int(v * k)) for v in p[6])
            q[7] = tuple(min(255, int(v * k)) for v in p[7])
            out.append(tuple(q))
        else:
            q = list(p)
            q[6] = tuple(min(255, int(v * k)) for v in p[6][:3])
            out.append(tuple(q))
    return out


def compile_model(parts, scale=1.0):
    """parts: боксы (x0,y0,z0,x1,y1,z1,цвет) и цилиндры
    ('cyl', cx, cy, z0, z1, r, цвет_боков, цвет_крышки, внутр_радиус, внутр_цвет, доски).
    Модель центрируется по основанию, масштабируется, считаются габариты."""
    ext = []
    for p in parts:
        if p[0] == 'cyl':
            _, cx, cy, z0, z1, r = p[:6]
            ext.append((cx - r, cy - r, z0, cx + r, cy + r, z1))
        else:
            ext.append(tuple(p[:6]))
    ext = np.array(ext, np.float32)
    mx = (ext[:, 0].min() + ext[:, 3].max()) / 2.0
    my = (ext[:, 1].min() + ext[:, 4].max()) / 2.0
    boxes, cyls = [], []
    for p in parts:
        if p[0] == 'cyl':
            _, cx, cy, z0, z1, r, sc, cc, ir, ic, st = p
            cyls.append(((cx - mx) * scale, (cy - my) * scale, z0 * scale, z1 * scale, r * scale,
                         tuple(float(v) for v in sc[:3]), tuple(float(v) for v in cc[:3]),
                         ir * scale, None if ic is None else tuple(float(v) for v in ic[:3]), bool(st)))
        else:
            x0, y0, z0, x1, y1, z1, col = p
            boxes.append((((x0 - mx) * scale, (y0 - my) * scale, z0 * scale),
                          ((x1 - mx) * scale, (y1 - my) * scale, z1 * scale),
                          np.array(col[:3], np.float32)))
    hx = max(abs(ext[:, 0].min() - mx), abs(ext[:, 3].max() - mx)) * scale
    hy = max(abs(ext[:, 1].min() - my), abs(ext[:, 4].max() - my)) * scale
    top = float(ext[:, 5].max()) * scale
    return {'boxes': boxes, 'cyls': cyls, 'hx': float(hx), 'hy': float(hy), 'top': top,
            'rad': float(math.hypot(hx, hy))}


def _shelf_parts(seed=5):
    """Длинный стеллаж-секция: 4 полки, стойки, задняя стенка и много коробок. Секции ставятся
    в ряд вдоль стены (см. place_furniture), получаются длинные стеллажи. В середине каждой
    полки оставлено свободное место — там может лежать батарейка."""
    wood, dkw, metal = (105, 76, 53), (78, 56, 40), (95, 101, 102)
    W, D, H = 2.7, 1.1, 2.6
    parts = []
    for x0 in (0.0, W - .14):
        for y0 in (0.0, D - .14):
            parts.append((x0, y0, 0, x0 + .14, y0 + .14, H, metal))
    parts.append((.14, D - .06, .1, W - .14, D, H - .05, dkw))
    boards = (.10, .76, 1.42, 2.08)
    for z in boards:
        parts.append((0, 0, z, W, D, z + .09, wood))
    parts.append((0, 0, H - .09, W, D, H, wood))
    # продольные раскосы сзади — металлическая рама
    parts.append((.14, D - .10, 1.0, W - .14, D - .06, 1.06, metal))
    parts.append((.14, D - .10, 1.76, W - .14, D - .06, 1.82, metal))
    rs = np.random.RandomState(seed)
    cols = [(150, 112, 68), (138, 102, 62), (162, 124, 78), (120, 88, 56),
            (94, 105, 91), (120, 70, 52), (172, 150, 112), (84, 90, 86)]
    for z in boards:
        top = z + .09
        for x0, x1 in ((.18, 1.05), (1.65, 2.52)):
            x = x0
            while x1 - x > .22:
                if rs.rand() < .12:                      # просвет между коробками
                    x += rs.uniform(.08, .2)
                    continue
                w = min(rs.uniform(.40, .70), x1 - x)
                h, d = rs.uniform(.22, .50), rs.uniform(.50, .82)
                c = cols[int(rs.randint(len(cols)))]
                parts.append((x, .16, top, x + w, .16 + d, top + h, c))
                x += w + rs.uniform(.02, .08)
    return parts


