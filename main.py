class Canvas:
    """Маленький холст для рисования пиксельных спрайтов (без pygame)."""

    def __init__(self, n=32):
        self.n = n
        self.rgb = np.zeros((n, n, 3), np.float32)
        self.a = np.zeros((n, n), bool)
        self.yy, self.xx = np.mgrid[0:n, 0:n].astype(np.float32)

    def paint(self, m, c):
        self.rgb[m] = c
        self.a[m] = True

    def rect(self, x0, y0, x1, y1, c):
        n = self.n
        x0, y0, x1, y1 = [int(round(v)) for v in (x0, y0, x1, y1)]
        x0, y0, x1, y1 = max(x0, 0), max(y0, 0), min(x1, n), min(y1, n)
        if x1 <= x0 or y1 <= y0:
            return
        self.rgb[y0:y1, x0:x1] = c
        self.a[y0:y1, x0:x1] = True

    def ellipse(self, cx, cy, rx, ry, c):
        m = ((self.xx - cx) / rx) ** 2 + ((self.yy - cy) / ry) ** 2 <= 1.0
        self.paint(m, c)

    def line(self, x0, y0, x1, y1, c, w=1.0):
        dx, dy = x1 - x0, y1 - y0
        l2 = max(dx * dx + dy * dy, 1e-6)
        t = np.clip(((self.xx - x0) * dx + (self.yy - y0) * dy) / l2, 0.0, 1.0)
        d2 = (self.xx - (x0 + t * dx)) ** 2 + (self.yy - (y0 + t * dy)) ** 2
        self.paint(d2 <= (w / 2.0) ** 2, c)

    def speckle(self, amt, seed=1):
        rs = np.random.RandomState(seed)
        nz = rs.randint(-amt, amt + 1, (self.n, self.n, 1)).astype(np.float32)
        self.rgb += nz * self.a[..., None]

    def outline(self, k=0.5):
        ap = np.pad(self.a, 1)
        inner = ap[:-2, 1:-1] & ap[2:, 1:-1] & ap[1:-1, :-2] & ap[1:-1, 2:]
        edge = self.a & ~inner
        self.rgb[edge] *= k

    def finish(self):
        return np.clip(self.rgb, 0, 255).astype(np.float32), self.a.copy()


def _mul(col, k):
    return np.array(col, np.float32) * k


def spr_barrel(variant=0):
    """Объёмная бочка: выпуклый корпус, эллиптическая крышка, обручи и блики."""
    c = Canvas(32)
    if variant == 0:
        dark, mid, light = (78, 72, 62), (142, 132, 112), (184, 174, 150)
        hoop, lid = (62, 70, 78), (158, 150, 132)
    else:
        dark, mid, light = (70, 48, 30), (132, 92, 54), (174, 126, 76)
        hoop, lid = (58, 60, 62), (144, 104, 66)

    # Контактная тень и нижняя кромка
    c.ellipse(16, 29, 12.0, 2.4, (24, 21, 18))
    # Бочкообразный корпус с выпуклыми боками
    for y in range(5, 30):
        t = (y - 5) / 24.0
        half = 8.0 + 3.0 * math.sin(math.pi * t)
        for x in range(max(0, int(16-half)), min(32, int(17+half))):
            u = (x - 16) / max(half, 1)
            shade = 1.0 - 0.48*u*u
            if x < 15:
                shade *= 1.13
            elif x > 23:
                shade *= 0.70
            plank = (x // 4) % 3
            base = np.array((mid, light, dark)[plank], np.float32)
            c.rgb[y, x] = np.clip(base * shade, 0, 255)
            c.a[y, x] = True
    # Обручи с металлическим бликом и тенью
    for y in (10, 11, 23, 24):
        xs = np.nonzero(c.a[y])[0]
        if xs.size:
            c.rect(int(xs.min()), y, int(xs.max())+1, y+1, hoop)
            c.rect(int(xs.min())+1, y, int(xs.max()), y+1, _mul(hoop, 1.28))
    # Верхняя крышка: несколько эллипсов дают ощущение глубины
    c.ellipse(16, 5, 9.8, 3.4, dark)
    c.ellipse(16, 4.5, 8.8, 2.8, lid)
    c.ellipse(16, 4.2, 6.6, 1.8, _mul(lid, 0.78))
    c.line(10, 4, 22, 4, _mul(light, 0.72), 1.0)
    c.speckle(3, 3 + variant)
    c.outline(0.48)
    return c.finish()

