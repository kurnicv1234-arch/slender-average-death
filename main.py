    def pick_target(self):
        best, bd = None, 9
        for it in self.items:
            if it.taken:
                continue
            dx, dy = it.x - self.px, it.y - self.py
            d = math.hypot(dx, dy)
            if d > 2.1 or d < 0.05:
                continue
            if not self.line_clear(self.px, self.py, it.x, it.y):
                continue
            ang = (math.atan2(dy, dx) - self.yaw + math.pi) % (2 * math.pi) - math.pi
            if abs(ang) < 0.55 and d < bd:
                best, bd = it, d
        self.target = best
        if self.mode == 'explore' and best and self.hint_t > 0:
            self.hint_t = min(self.hint_t, 0.5)

