# ------------------------------------------------------------------ запуск
def start_music():
    """Запускает саундтрек по кругу. Работает и на телефоне/ПК, и в браузере (pygbag, формат .ogg).
    Возвращает True, если музыка пошла. Любая ошибка звука игру не ломает."""
    try:
        if not pygame.mixer.get_init():
            pygame.mixer.init()
        here = os.path.dirname(os.path.abspath(__file__)) if '__file__' in globals() else '.'
        path = next((c for c in (os.path.join(here, SOUNDTRACK), SOUNDTRACK) if os.path.exists(c)), None)
        if path is None:
            return False
        pygame.mixer.music.load(path)
        pygame.mixer.music.set_volume(MUSIC_VOLUME)
        pygame.mixer.music.play(-1)
        return True
    except Exception:
        return False


def is_mobile():
    return (sys.platform == 'android' or 'ANDROID_ARGUMENT' in os.environ
            or 'ANDROID_ROOT' in os.environ and sys.platform != 'win32' and 'DISPLAY' not in os.environ)


LOGICAL_W, LOGICAL_H = 1280, 720  # единый игровой кадр 16:9


def make_screen():
    # Игровая сцена всегда 16:9. На телефоне используем весь экран,
    # на ПК — изменяемое окно; масштабирование выполняется в главном цикле.
    if sys.platform == 'emscripten':
        return pygame.display.set_mode((LOGICAL_W, LOGICAL_H), pygame.SCALED)
    if is_mobile():
        return pygame.display.set_mode((0, 0), pygame.FULLSCREEN)
    info = pygame.display.Info()
    w = min(LOGICAL_W, max(640, info.current_w - 60))
    h = min(int(w * 9 / 16), max(360, info.current_h - 110))
    w = int(h * 16 / 9) if h < int(w * 9 / 16) else w
    return pygame.display.set_mode((w, h), pygame.RESIZABLE)


def fit_viewport(display_size):
    """Прямоугольник 16:9, вписанный в физический экран без искажения."""
    dw, dh = display_size
    scale = min(dw / LOGICAL_W, dh / LOGICAL_H)
    vw, vh = int(LOGICAL_W * scale), int(LOGICAL_H * scale)
    return pygame.Rect((dw - vw) // 2, (dh - vh) // 2, vw, vh)


def pointer_to_game(x, y, viewport):
    # Координаты указателя из окна/экрана в логические координаты игры.
    return ((x - viewport.x) * LOGICAL_W / max(1, viewport.w),
            (y - viewport.y) * LOGICAL_H / max(1, viewport.h))


async def main():
    try:
        pygame.mixer.pre_init(44100, -16, 2, 1024)
    except Exception:
        pass
    pygame.init()
    pygame.display.set_caption(GAME_TITLE)
    display = make_screen()
    screen = pygame.Surface((LOGICAL_W, LOGICAL_H)).convert()
    viewport = fit_viewport(display.get_size())
    game = Game(screen)
    music_on = start_music()       # в браузере звук разрешён только после касания — повторим при первом вводе
    clock = pygame.time.Clock()
    last = time.perf_counter()
    running = True
    while running:
        for e in pygame.event.get():
            t = e.type
            if t in (pygame.FINGERDOWN, pygame.MOUSEBUTTONDOWN, pygame.KEYDOWN):
                try:
                    if not music_on or not pygame.mixer.music.get_busy():
                        music_on = start_music()
                except Exception:
                    pass
            if t == pygame.QUIT:
                running = False
            elif t == pygame.FINGERDOWN:
                game.finger_mode = True
                raw_x, raw_y = e.x * display.get_width(), e.y * display.get_height()
                if not viewport.collidepoint(raw_x, raw_y):
                    continue
                x, y = pointer_to_game(raw_x, raw_y, viewport)
                game.on_down(e.finger_id, x, y)
            elif t == pygame.FINGERMOTION:
                raw_x, raw_y = e.x * display.get_width(), e.y * display.get_height()
                x, y = pointer_to_game(raw_x, raw_y, viewport)
                x, y = clamp(x, 0, LOGICAL_W), clamp(y, 0, LOGICAL_H)
                game.on_move(e.finger_id, x, y)
            elif t == pygame.FINGERUP:
                raw_x, raw_y = e.x * display.get_width(), e.y * display.get_height()
                x, y = pointer_to_game(raw_x, raw_y, viewport)
                x, y = clamp(x, 0, LOGICAL_W), clamp(y, 0, LOGICAL_H)
                game.on_up(e.finger_id, x, y)
            elif t in (pygame.MOUSEBUTTONDOWN, pygame.MOUSEMOTION, pygame.MOUSEBUTTONUP):
                if game.finger_mode or getattr(e, 'touch', False):
                    continue
                if t == pygame.MOUSEBUTTONDOWN and e.button == 1 and not viewport.collidepoint(*e.pos):
                    continue
                mx, my = pointer_to_game(*e.pos, viewport)
                mx, my = clamp(mx, 0, LOGICAL_W), clamp(my, 0, LOGICAL_H)
                if t == pygame.MOUSEBUTTONDOWN and e.button == 1:
                    game.on_down(-1, mx, my)
                elif t == pygame.MOUSEMOTION and e.buttons[0]:
                    game.on_move(-1, mx, my)
                elif t == pygame.MOUSEBUTTONUP and e.button == 1:
                    game.on_up(-1, mx, my)
            elif t == pygame.KEYDOWN:
                game.key_down(e.key)
            elif t == pygame.VIDEORESIZE and not is_mobile():
                display = pygame.display.get_surface()
                viewport = fit_viewport(display.get_size())
        now = time.perf_counter()
        dt = clamp(now - last, 0.001, 0.08)
        last = now
        game.fps = damp(game.fps, 1.0 / dt, 4, dt)
        game.update(dt)
        game.draw()
        if game.quit_requested:
            running = False
        display.fill((0, 0, 0))
        viewport = fit_viewport(display.get_size())
        scaled_frame = pygame.transform.smoothscale(screen, viewport.size)
        display.blit(scaled_frame, viewport.topleft)
        pygame.display.flip()
        clock.tick(TARGET_FPS)
        await asyncio.sleep(0)
    pygame.quit()


if __name__ == '__main__':
    asyncio.run(main())
