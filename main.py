def build_maze():
    # Стартовая комната стала компактной: 3x3 клетки и один узкий выход.
    # Выход закрыт отдельной дверью, которая требует все 8 книг.
    rows = [list(row) for row in MAZE_ROWS]
    for y in (4, 5):
        for x in range(42, 47):
            rows[y][x] = '#'
    for y in (6, 7, 8):
        rows[y][42] = '#'
        rows[y][46] = '#'
    # Боковой коридор за запертой дверью. Основной выход в лабиринт
    # остаётся снизу комнаты, чтобы игрок мог собрать книги.
    for x in range(46, 58):
        rows[7][x] = '.'
    for x in (42, 43, 45, 46):
        rows[9][x] = '#'
    return [''.join(row) for row in rows]


