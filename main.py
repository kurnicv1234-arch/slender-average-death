    def door_segment(self, door):
        """Плоскость двери в мире: петля в одной точке, створка поворачивается вокруг неё."""
        hx, hy = door['dir']
        a = door['angle'] * door.get('sgn', 1.0)
        dx = hx * math.cos(a) - hy * math.sin(a)
        dy = hx * math.sin(a) + hy * math.cos(a)
        ox, oy = door['hinge']
        return (ox, oy), (ox + dx * door['len'], oy + dy * door['len'])

    def door_blocks(self, x, y, radius=0.22):
        for door in self.doors:
            if door['angle'] > 1.45:
                continue
            (ax, ay), (bx, by) = self.door_segment(door)
            vx, vy = bx - ax, by - ay
            den = vx * vx + vy * vy
            t = clamp(((x - ax) * vx + (y - ay) * vy) / max(den, 1e-8), 0.0, 1.0)
            if math.hypot(x - (ax + t * vx), y - (ay + t * vy)) < radius + 0.035:
                return True
        return False

    def nearby_door(self):
        candidates = [
            d for d in self.doors
            if math.hypot(d['x'] - self.px, d['y'] - self.py) < 1.65
        ]
        if not candidates:
            return None
        door = min(candidates, key=lambda d: math.hypot(d['x'] - self.px, d['y'] - self.py))
        ang = (math.atan2(door['y'] - self.py, door['x'] - self.px) - self.yaw + math.pi) % (2 * math.pi) - math.pi
        return door if abs(ang) < 0.9 else None

    def toggle_door(self, door):
        if door.get('locked_books'):
            if self.count < 8:
                self.toast('Дверь заперта: найдите все 8 книг (%d/8)' % self.count)
                return
            if not door['open']:
                door['open'] = True
                self.cutscene_pending = door
                self.vx = self.vy = 0.0
                self.ptrs.clear()
                self.toast('Дверь открывается...')
            return
        if door.get('boarded'):
            if not self.has_crowbar:
                self.toast('Заколочено')
                return
            door['boarded'] = False
            self.sl_enrage(RAGE_TIME * (1.0 + 0.5 * self.count / 8.0))
        grp = door.get('group')
        doors = [d for d in self.doors if d.get('group') == grp] if grp is not None else [door]
        name = 'Шкаф' if grp is not None else 'Дверь'
        if door['open']:
            if grp is not None:
                fx, fy = door['front']
                sx, sy = -fy, fx
                ax, ay = door['x'] - sx * 0.5, door['y'] - sy * 0.5
                t = clamp((self.px - ax) * sx + (self.py - ay) * sy, 0.0, 1.0)
                near = math.hypot(self.px - (ax + sx * t), self.py - (ay + sy * t)) < 0.36
            else:
                near = math.hypot(door['x'] - self.px, door['y'] - self.py) < 0.62
            if near:
                return
            for d in doors:
                d['open'] = False
        else:
            for d in doors:
                if not d.get('fixed'):
                    ax, ay = d['axis']
                    side = (self.px - d['x']) * ax + (self.py - d['y']) * ay
                    d['sgn'] = 1.0 if side > 0 else -1.0       # открывается от игрока
                d['open'] = True

