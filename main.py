    def draw(self):
        scr, U, sw, sh = self.screen, self.U, self.sw, self.sh
        shk = 0.03 * self.gaze ** 2 + (0.02 if self.dead else 0.0) + 0.01 * self.sl_glitch
        cam = (self.px, self.py,
               self.yaw + self.sway_yaw + shk * math.sin(self.t * 47.0),
               self.pitch + self.nod + shk * math.sin(self.t * 53.0 + 1.0),
               self.camh + getattr(self, 'bob_h', 0.0))
        f = self.R.f
        k = f * getattr(self, 'last_dt', 0.0167) * 0.7
        # getattr оставлен как дополнительная защита для любых
        # переходных состояний/старых экземпляров Game.
        yaw_vel = getattr(self, 'yaw_vel', 0.0)
        pitch_vel = getattr(self, 'pitch_vel', 0.0)
        blur = (clamp(yaw_vel * k, -7, 7), clamp(-pitch_vel * k, -7, 7))
        sprites = []
        for it in self.items:
            if it.taken or (it is self.cur and self.insp > 0.02 and not self.leaving):
                pass
            if it.taken:
                continue
            sprites.append({'x': it.x, 'y': it.y, 'size': it.size, 'tex': it.tex, 'glow': it.glow,
                            'depth_hint': (lambda c, it=it: (it.x - c[0]) * math.cos(c[2]) + (it.y - c[1]) * math.sin(c[2]))})
        models = []
        cy_, sy_ = math.cos(self.yaw), math.sin(self.yaw)
        for d in self.decor:
            ddx, ddy = d['x'] - self.px, d['y'] - self.py
            if ddx * ddx + ddy * ddy > 100.0:
                continue
            depth = ddx * cy_ + ddy * sy_
            if depth < -d['rad']:
                continue
            if depth > 0.3 and abs(-ddx * sy_ + ddy * cy_) > depth * 1.25 + d['rad'] + 0.3:
                continue                                  # вне поля зрения
            models.append({'model': d['model'], 'x': d['x'], 'y': d['y'], 'c': d['c'], 's': d['s'],
                           'depth': depth})
        S = self.sl
        sdx_, sdy_ = S['x'] - self.px, S['y'] - self.py
        sdep = sdx_ * cy_ + sdy_ * sy_
        s_vis = self.dead or (sdep > -0.6 and sdx_ * sdx_ + sdy_ * sdy_ < 144.0
                              and abs(-sdx_ * sy_ + sdy_ * cy_) <= max(sdep, 0.3) * 1.25 + 0.6)
        if (S['state'] == 'present' or self.dead) and not self.won and s_vis:
            if self.dead or not (self.gaze > 0.4 and self.sl_rs.rand() < self.gaze * 0.22):
                fx_, fy_ = self.px - S['x'], self.py - S['y']
                ll = math.hypot(fx_, fy_) or 1.0
                yo = math.atan2(fx_ / ll, -fy_ / ll)
                models.append({'model': self.sl_model, 'x': S['x'], 'y': S['y'],
                               'c': math.cos(yo), 's': math.sin(yo),
                               'depth': sdep, 'glow': 0.14})
        for bt in self.batteries:
            if bt['got']:
                continue
            bdx, bdy = bt['x'] - self.px, bt['y'] - self.py
            if bdx * bdx + bdy * bdy > 64.0:
                continue
            bdep = bdx * cy_ + bdy * sy_
            if bdep < -0.3 or (bdep > 0.3 and abs(-bdx * sy_ + bdy * cy_) > bdep * 1.25 + 0.4):
                continue
            models.append({'model': bt['model'], 'x': bt['x'], 'y': bt['y'], 'c': 1.0, 's': 0.0,
                           'depth': bdep, 'glow': 0.16})
        self.R.models_geom = models
        geom = []
        for d in self.doors:
            ddx, ddy = d['x'] - self.px, d['y'] - self.py
            dist2 = ddx * ddx + ddy * ddy
            if dist2 > 196.0:
                continue
            if dist2 > 4.0 and ddx * math.cos(self.yaw) + ddy * math.sin(self.yaw) < -0.5:
                continue
            a_, b_ = self.door_segment(d)
            geom.append((a_, b_, self.door_tex_boarded if d.get('boarded') else d.get('tex', self.door_tex)))
        self.R.doors_geom = geom
        frame = self.R.render(cam, sprites, blur, self.t)
        surf = pygame.image.frombuffer(frame.tobytes(), (self.bw, self.bh), 'RGB')
        scr.blit(pygame.transform.scale(surf, (sw, sh)), (0, 0))

        sc = sw / self.bw
        if not self.dead:
            self.draw_motes(cam, sc)
        if self.menu_state != 'game':
            self.draw_menu()
            return
        if self.cutscene_active:
            self.draw_cutscene()
            return
        self.draw_fear_fx()
        if self.mode == 'explore':
            self.draw_explore_hud(cam, sc)
        else:
            self.draw_inspect(cam, sc)
        self.draw_common()
        self.draw_death()

