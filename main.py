    def free(self, x, y, r=0.22):
        for cx, cy in ((x - r, y - r), (x + r, y - r), (x - r, y + r), (x + r, y + r)):
            ix, iy = int(math.floor(cx)), int(math.floor(cy))
            if iy < 0 or ix < 0 or iy >= self.R.mh or ix >= self.R.mw or self.R.map[iy, ix] > 0:
                return False
        for sx_, sy_, co_, so_, hx_, hy_ in self.solids:
            dx_, dy_ = x - sx_, y - sy_
            if dx_ * dx_ + dy_ * dy_ > 1.0:
                continue
            lx_ = co_ * dx_ + so_ * dy_
            ly_ = -so_ * dx_ + co_ * dy_
            qx_ = max(-hx_, min(hx_, lx_))
            qy_ = max(-hy_, min(hy_, ly_))
            if (lx_ - qx_) ** 2 + (ly_ - qy_) ** 2 < 0.17 * 0.17:
                return False
        if self.door_blocks(x, y, r):
            return False
        return True

    def update(self, dt):
        if self.menu_state != 'game':
            return
        self.t += dt
        self.last_dt = dt
        for door in self.doors:
            goal = 1.0 if door['open'] else 0.0
            step = dt / 0.9
            if door['prog'] < goal:
                door['prog'] = min(goal, door['prog'] + step)
            elif door['prog'] > goal:
                door['prog'] = max(goal, door['prog'] - step)
            p = door['prog']
            door['angle'] = (p * p * (3.0 - 2.0 * p)) * 1.57

        if self.cutscene_active:
            self.cutscene_t += dt
            if self.cutscene_t >= 2.05 and not self.cutscene_scream_played:
                self.cutscene_scream_played = True
                self.play_cutscene_scream()
            if self.cutscene_t >= 4.85:
                self.cutscene_active = False
                self.won = True
                self.toast('Вы выбрались из дома!')
            return
        if self.cutscene_pending and self.cutscene_pending.get('prog', 0.0) >= 0.99:
            self.begin_cutscene()
            return
        if self.won:
            return
        if self.dead:
            self.update_dead(dt)
            return
        U = self.U
        # клавиатура (для проверки на компьютере)
        kb = pygame.key.get_pressed() if hasattr(pygame, 'key') else None
        mvf = mvs = 0.0
        klx = kly = 0.0
        if kb:
            mvf = (1 if kb[pygame.K_w] else 0) - (1 if kb[pygame.K_s] else 0)
            mvs = (1 if kb[pygame.K_d] else 0) - (1 if kb[pygame.K_a] else 0)
            klx = (1 if kb[pygame.K_RIGHT] else 0) - (1 if kb[pygame.K_LEFT] else 0)
            kly = (1 if kb[pygame.K_UP] else 0) - (1 if kb[pygame.K_DOWN] else 0)

