def _rect_overlap(a, b, margin=0.03):
    """Пересечение двух повёрнутых прямоугольников (x, y, c, s, hx, hy), SAT."""
    ax, ay, ac, as_, ahx, ahy = a
    bx, by, bc, bs, bhx, bhy = b
    dx, dy = bx - ax, by - ay
    for ux, uy in ((ac, as_), (-as_, ac), (bc, bs), (-bs, bc)):
        ra = ahx * abs(ux * ac + uy * as_) + ahy * abs(-ux * as_ + uy * ac)
        rb = bhx * abs(ux * bc + uy * bs) + bhy * abs(-ux * bs + uy * bc)
        if abs(dx * ux + dy * uy) >= ra + rb + margin:
            return False
    return True


def _in_rect(x, y, r, pad=0.0):
    rx, ry, c, s, hx, hy = r
    dx, dy = x - rx, y - ry
    return abs(c * dx + s * dy) <= hx + pad and abs(-s * dx + c * dy) <= hy + pad


def _fine_reach(m, solids, start, res=3):
    """Достижимые для игрока места на сетке в res раз мельче клетки (стены и мебель раздуты
    на радиус игрока). Возвращает (достижимые, занятые_мебелью)."""
    mh, mw = m.shape
    H, W = mh * res, mw * res
    ys = (np.arange(H) + 0.5) / res
    xs = (np.arange(W) + 0.5) / res
    wall = m[np.minimum(ys.astype(int), mh - 1)][:, np.minimum(xs.astype(int), mw - 1)] > 0
    infl = wall.copy()
    for _ in range(1):
        t = infl.copy()
        t[1:] |= infl[:-1]; t[:-1] |= infl[1:]
        t[:, 1:] |= infl[:, :-1]; t[:, :-1] |= infl[:, 1:]
        infl = t
    occ = np.zeros_like(infl)
    gx, gy = np.meshgrid(xs, ys)
    for (x, y, c, s, hx, hy) in solids:
        r = max(hx, hy) + PLAYER_RADIUS + 0.1
        x0, x1 = max(0, int((x - r) * res)), min(W, int((x + r) * res) + 1)
        y0, y1 = max(0, int((y - r) * res)), min(H, int((y + r) * res) + 1)
        if x1 <= x0 or y1 <= y0:
            continue
        dx, dy = gx[y0:y1, x0:x1] - x, gy[y0:y1, x0:x1] - y
        lx, ly = c * dx + s * dy, -s * dx + c * dy
        occ[y0:y1, x0:x1] |= (np.abs(lx) <= hx + PLAYER_RADIUS) & (np.abs(ly) <= hy + PLAYER_RADIUS)
    blocked = (infl | occ).ravel().tolist()
    sx_, sy_ = int(start[0] * res), int(start[1] * res)
    seen = bytearray(W * H)
    if blocked[sy_ * W + sx_]:
        return seen, occ.ravel()
    stack = [sy_ * W + sx_]
    seen[stack[0]] = 1
    while stack:
        i = stack.pop()
        x = i % W
        for j in ((i - 1) if x > 0 else -1, (i + 1) if x < W - 1 else -1, i - W, i + W):
            if 0 <= j < W * H and not seen[j] and not blocked[j]:
                seen[j] = 1
                stack.append(j)
    return seen, occ.ravel()


def place_furniture(m, models, forbid, closets, start, seed=7, density=1.0):
    """Расставляет мебель вдоль стен и по углам комнат и коридоров.
    Возвращает список предметов: {'x','y','kind','model','c','s','rad','sol'}.
    Проходы гарантированно остаются: перед мебелью ≥ ширины игрока, а в конце проверяется
    связность карты (мебель, перекрывающая путь, убирается)."""
    mh, mw = m.shape
    rs = np.random.RandomState(seed)
    # (кол-во, плоский?, мелкий — можно поворачивать вразнобой, предпочитать угол)
    spec = {
        'locker':  (22, False, False, 0.85), 'cabinet': (14, False, False, 0.7),
        'shelf':   (9,  False, False, 0.3),  'bed':     (14, False, False, 0.8),
        'bedside': (14, False, False, 0.9),  'desk':    (10, False, False, 0.5),
        'cart':    (9,  False, False, 0.4),  'table':   (12, False, True,  0.6),
        'chair':   (22, False, True,  0.5),  'stool':   (14, False, True,  0.7),
        'barrel':  (26, False, True,  0.9),  'crate':   (28, False, True,  0.9),
        'bin':     (16, False, True,  0.9),  'ivstand': (10, False, True,  0.8),
        'pallet':  (14, False, False, 0.4),  'wheel':   (8,  True,  True,  0.2),
        'skeleton':(6,  True,  True,  0.2),
    }
    closet_set = set(closets)

    def isfloor(x, y):
        return 0 <= x < mw and 0 <= y < mh and m[y, x] == 0

    def iswall(x, y):
        return not (0 <= x < mw and 0 <= y < mh) or m[y, x] > 0

    def allowed(x, y):
        px, py = x + 0.5, y + 0.5
        return all(math.hypot(px - fx, py - fy) >= fr for fx, fy, fr in forbid)

    corners, walls_ = [], []
    for y in range(mh):
        for x in range(mw):
            if not isfloor(x, y) or (x, y) in closet_set or not allowed(x, y):
                continue
            N, S, W_, E = iswall(x, y - 1), iswall(x, y + 1), iswall(x - 1, y), iswall(x + 1, y)
            if (N and S) or (W_ and E):
                continue                                    # узкий проход в 1 клетку — не загромождаем
            if not (N or S or W_ or E):
                continue
            (corners if (N or S) and (W_ or E) else walls_).append((x, y, N, S, W_, E))
    if not corners and not walls_:
        return []

    placed = []

    def front_clear(r, fxd, fyd, need=0.8):
        x, y, c, s, hx, hy = r
        # центр передней грани и боковые точки
        lat = (-fyd, fxd)
        half = hy if abs(fxd * c + fyd * s) > 0.7 else hx
        depth = hx if abs(fxd * c + fyd * s) > 0.7 else hy
        for off in (-half, 0.0, half):
            for k in range(1, int(need / 0.1) + 1):
                d = depth + k * 0.1
                wx = x + fxd * d + lat[0] * off
                wy = y + fyd * d + lat[1] * off
                if iswall(int(math.floor(wx)), int(math.floor(wy))):
                    return False
                for q in placed:
                    if _in_rect(wx, wy, q['sol'], 0.0):
                        return False
        return True

    todo = []
    for kind, (n, flat, small, cw) in spec.items():
        todo += [kind] * max(1, int(round(n * density)))
    todo = [todo[i] for i in rs.permutation(len(todo))]
    DIRS = {'N': (0, -1), 'S': (0, 1), 'W': (-1, 0), 'E': (1, 0)}

    for kind in todo:
        n_, flat, small, cw = spec[kind]
        for attempt in range(60):
            use_corner = corners and (not walls_ or rs.rand() < cw)
            pool = corners if use_corner else walls_
            gx, gy, N, S, W_, E = pool[int(rs.randint(len(pool)))]
            var = int(rs.randint(0, 2))
            model = models[kind][var]
            # к какой стене прижимаем спиной
            ws = [k for k, v in (('N', N), ('S', S), ('W', W_), ('E', E)) if v]
            back = ws[int(rs.randint(len(ws)))]
            bdx, bdy = DIRS[back]
            fxd, fyd = -bdx, -bdy
            jit = rs.uniform(-0.3, 0.3) if small else 0.0
            yaw_o = math.atan2(fxd, -fyd) + jit
            if flat:
                yaw_o = rs.uniform(0, 2 * math.pi)
            co, so = math.cos(yaw_o), math.sin(yaw_o)
            ex = abs(co) * model['hx'] + abs(so) * model['hy']
            ey = abs(so) * model['hx'] + abs(co) * model['hy']
            if ex > 0.47 or ey > 0.47:
                continue
            gap = 0.035
            if W_:
                px = gx + ex + gap
            elif E:
                px = gx + 1 - ex - gap
            else:
                px = gx + 0.5 + rs.uniform(-(0.5 - ex), 0.5 - ex)
            if N:
                py = gy + ey + gap
            elif S:
                py = gy + 1 - ey - gap
            else:
                py = gy + 0.5 + rs.uniform(-(0.5 - ey), 0.5 - ey)
            rect = (px, py, co, so, model['hx'], model['hy'])
            if any(_rect_overlap(rect, q['sol'], 0.03) for q in placed
                   if abs(q['x'] - px) < 1.5 and abs(q['y'] - py) < 1.5):
                continue
            if not flat and not front_clear(rect, fxd, fyd):
                continue
            placed.append({'x': px, 'y': py, 'kind': kind, 'model': model, 'c': co, 's': so,
                           'rad': model['rad'], 'sol': rect, 'flat': flat})
            if kind == 'shelf' and rs.rand() < 0.92:         # стеллаж продолжается вдоль стены — длинный ряд
                lx, ly = int(-fyd), int(fxd)
                sg = 1 if rs.rand() < 0.5 else -1
                for kk in range(1, 1 + int(rs.randint(1, 4))):
                    ngx, ngy = gx + lx * sg * kk, gy + ly * sg * kk
                    if not isfloor(ngx, ngy) or (ngx, ngy) in closet_set or not allowed(ngx, ngy):
                        break
                    if not iswall(ngx + bdx, ngy + bdy):
                        break
                    r2 = (px + lx * sg * kk, py + ly * sg * kk, co, so, model['hx'], model['hy'])
                    if any(_rect_overlap(r2, q['sol'], 0.03) for q in placed):
                        break
                    if not front_clear(r2, fxd, fyd):
                        break
                    m2 = models[kind][(var + kk) % 2]       # секции чередуются — ряд не выглядит копией
                    placed.append({'x': r2[0], 'y': r2[1], 'kind': kind, 'model': m2, 'c': co, 's': so,
                                   'rad': m2['rad'], 'sol': r2, 'flat': flat})
            break

    # ---- проверка связности: мебель не должна отрезать части карты
    solids = [p['sol'] for p in placed if not p['flat']]
    try:
        base, _ = _fine_reach(m, [], start)
        for _ in range(8):
            solids = [p['sol'] for p in placed if not p['flat']]
            now, occ = _fine_reach(m, solids, start)
            stranded = [i for i in range(len(base)) if base[i] and not now[i] and not occ[i]]
            if not stranded:
                break
            res = 3
            W = mw * res
            pts = [((i % W) / res, (i // W) / res) for i in stranded[::max(1, len(stranded) // 60)]]
            kill = [p for p in placed if not p['flat'] and any(
                math.hypot(p['x'] - qx, p['y'] - qy) < 1.4 for qx, qy in pts)]
            if not kill:
                break
            placed = [p for p in placed if p not in kill]
    except Exception:
        pass
    return placed



